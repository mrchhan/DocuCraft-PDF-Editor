"""Build the Shadow brand assets from the owner's original artwork and (re)generate core/branding.py,
which embeds them inside the program. Dev-only (needs Pillow). Run: python scripts/make_branding.py

Source artwork: assets/branding/shadow/source/original-dark.png and original-light.png (the owner's own files).
The face is cropped as-is from those images; nothing is redrawn."""
from __future__ import annotations

import base64
import hashlib
import io
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "branding" / "shadow" / "source"
OUT = ROOT / "assets" / "branding" / "shadow"
FACE_BOX = (590, 0, 1090, 500)              # square around the hood and face in the 1672x941 originals
BLUE, ORANGE = (46, 155, 255), (255, 138, 31)


def emblem(src: Path, size: int = 1024) -> Image.Image:
    """The face in a circle with the blue / orange ring from the Shadow banners."""
    big = size * 2
    face = Image.open(src).convert("RGB").crop(FACE_BOX).resize((big, big), Image.LANCZOS)
    ring = int(big * 0.035)
    mask = Image.new("L", (big, big), 0)
    ImageDraw.Draw(mask).ellipse((ring, ring, big - ring, big - ring), fill=255)
    out = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    out.paste(face, (0, 0), mask)
    grad = Image.new("RGBA", (big, big))
    gd = ImageDraw.Draw(grad)
    gd.rectangle((0, 0, big // 2, big), fill=BLUE + (255,))
    gd.rectangle((big // 2, 0, big, big), fill=ORANGE + (255,))
    ring_mask = Image.new("L", (big, big), 0)
    rd = ImageDraw.Draw(ring_mask)
    rd.ellipse((0, 0, big - 1, big - 1), fill=255)
    rd.ellipse((ring, ring, big - ring - 1, big - ring - 1), fill=0)
    out.paste(grad, (0, 0), ring_mask)
    return out.resize((size, size), Image.LANCZOS)


def png(im: Image.Image, size: int | None = None) -> bytes:
    if size:
        im = im.resize((size, size), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=True)
    return buf.getvalue()


def jpg(path: Path, width: int) -> bytes:
    im = Image.open(path).convert("RGB")
    im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=88, optimize=True)
    return buf.getvalue()


def b64(raw: bytes) -> str:
    s = base64.b64encode(raw).decode()
    return "\n".join(s[i:i + 100] for i in range(0, len(s), 100))


def main() -> None:
    dark, light = emblem(SRC / "original-dark.png"), emblem(SRC / "original-light.png")
    dark.save(OUT / "shadow-emblem-dark.png")
    light.save(OUT / "shadow-emblem-light.png")
    (ROOT / "assets" / "images").mkdir(exist_ok=True)
    dark.resize((512, 512), Image.LANCZOS).save(ROOT / "assets" / "images" / "logo.png")
    dark.save(ROOT / "assets" / "icons" / "docucraft.ico", sizes=[(s, s) for s in (16, 24, 32, 48, 64, 128, 256)])

    items = {
        "EMBLEM_DARK": png(dark, 256), "EMBLEM_LIGHT": png(light, 256),
        "FULL_DARK": jpg(SRC / "original-dark.png", 1280), "FULL_LIGHT": jpg(SRC / "original-light.png", 1280),
    }
    wm = light.resize((256, 256), Image.LANCZOS)                       # watermark source (faded at stamp time)
    items["WATERMARK"] = png(wm)
    body = []
    for name, raw in items.items():
        body.append(f'_{name} = """\n{b64(raw)}\n"""\n_{name}_SHA = "{hashlib.sha256(raw).hexdigest()}"\n')
    src = '''"""Shadow brand identity, embedded in the program (generated by scripts/make_branding.py - do not edit by hand).

The logo is compiled into this module instead of being loaded from a file, so replacing an image on disk does not
change what DocuCraft shows, and every byte is checked against a SHA-256 digest before use. Qt-free."""
from __future__ import annotations

import base64
import hashlib

APP_NAME = "DocuCraft"
STUDIO = "Shadow Creative Studio"
OWNER = "Hassan Malik"
PHONE = "+923363330884"
EMAIL = "hassanmalik.net@gmail.com"
CREATED_BY = f"Created by {OWNER}"
CONTACT_LINE = f"{CREATED_BY}  \\u00b7  {PHONE}  \\u00b7  {EMAIL}"
STAMP_TEXT = f"Made with {APP_NAME}"                         # also the marker that stops pages being stamped twice
STAMP_LINE = f"{STAMP_TEXT} \\u00b7 {STUDIO} \\u00b7 {OWNER} \\u00b7 {PHONE} \\u00b7 {EMAIL}"
STAMP_SHORT = f"{STAMP_TEXT} \\u00b7 {STUDIO}"

''' + "\n".join(body) + '''

_ASSETS = {
    "emblem_dark": (_EMBLEM_DARK, _EMBLEM_DARK_SHA), "emblem_light": (_EMBLEM_LIGHT, _EMBLEM_LIGHT_SHA),
    "full_dark": (_FULL_DARK, _FULL_DARK_SHA), "full_light": (_FULL_LIGHT, _FULL_LIGHT_SHA),
    "watermark": (_WATERMARK, _WATERMARK_SHA),
}


def asset(name: str) -> bytes:
    """Return one embedded image (PNG/JPEG bytes). Raises if the data was tampered with or damaged."""
    data, digest = _ASSETS[name]
    raw = base64.b64decode("".join(data.split()))
    if hashlib.sha256(raw).hexdigest() != digest:
        raise RuntimeError("DocuCraft branding data is damaged. Please reinstall the application.")
    return raw


def verify() -> bool:
    try:
        for k in _ASSETS:
            asset(k)
        return True
    except Exception:                                                  # noqa: BLE001
        return False
'''
    (ROOT / "core" / "branding.py").write_text(src, encoding="utf-8")
    print("wrote core/branding.py", len(src) // 1024, "KB")


if __name__ == "__main__":
    main()
